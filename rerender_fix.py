def fig7_abruptness(arms, out):
    labels = [m[0] for m in METRICS]
    x = np.arange(len(labels))
    width = 0.2

    fig, ax = plt.subplots(figsize=(7.2, 2.9))
    for i, (arm, label, _n, last, colour, _ls) in enumerate(ARMS):
        vals = []
        for _disp, key, _d in METRICS:
            v = abruptness(arms, arm, key, last) if key in arms[arm] else None
            vals.append(v if v is not None else np.nan)
        ax.bar(x + (i - 1.5) * width, vals, width, label=label, color=colour)

    ax.axhline(100, ls="--", lw=0.8, color="0.35")
    ax.text(0.02, 108, "100% = non-monotonic", fontsize=6, color="0.35",
            transform=ax.get_yaxis_transform())

    ax.set_yscale("symlog", linthresh=10)
    ticks = [0, 25, 50, 100, 200, 400, 700]
    ax.set_yticks(ticks)
    ax.set_yticklabels([str(t) for t in ticks])
    ax.set_ylim(0, 800)
    ax.set_ylabel(r"abruptness (max per-gen $|\Delta|$ / total $|\Delta|$, %)")
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=30, ha="right")
    ax.set_title("Leading signals have gradual onset; benchmark movement is non-monotonic")
    ax.legend(loc="upper left", frameon=False, ncol=1)
    ax.spines[["top", "right"]].set_visible(False)
    fig.savefig(out, format="pdf")
