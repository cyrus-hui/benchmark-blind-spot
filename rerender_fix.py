def run_canary(arms, verbose=True):
    fails = []
    for desc, fn, exp, tol in CANARY:
        try:
            got = fn(arms)
        except Exception as exc:                      # noqa: BLE001
            fails.append((desc, "ERROR: %s" % exc, exp))
            continue
        ok = abs(got - exp) <= tol
        if verbose:
            print("  [%s] %-28s paper %10.4f   computed %10.4f"
                  % ("ok" if ok else "FAIL", desc, exp, got))
        if not ok:
            fails.append((desc, got, exp))
    if fails:
        print("\nCANARY FAILED — figdata.json does not match the paper. "
              "Do NOT ship these figures.", file=sys.stderr)
        for desc, got, exp in fails:
            print("    %s: expected %s, got %s" % (desc, exp, got), file=sys.stderr)
        return False
    if verbose:
        print("  canary passed: %d/%d printed values reproduced\n" % (len(CANARY), len(CANARY)))
    return True


