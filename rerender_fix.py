def backup(path):
    """Copy an existing figure aside before overwriting it."""
    if os.path.exists(path):
        dest = path + ".bak"
        shutil.copy2(path, dest)
        return dest
    return None


def load(path):
    with open(path) as fh:
        return json.load(fh)["arms"]


def gens(arms, arm, metric):
    """Sorted integer generations available for (arm, metric)."""
    if metric not in arms[arm]:
        return []
    return sorted(int(g) for g in arms[arm][metric])


def seed_vals(arms, arm, metric, gen):
    return arms[arm][metric][str(gen)]


def mean_at(arms, arm, metric, gen):
    v = seed_vals(arms, arm, metric, gen)
    return sum(v.values()) / len(v)


def series(arms, arm, metric, upto=None):
    """(gen_list, mean_list) for a metric, optionally truncated at `upto`."""
    gs = [g for g in gens(arms, arm, metric) if upto is None or g <= upto]
    return gs, [mean_at(arms, arm, metric, g) for g in gs]


def pct_series(arms, arm, metric, upto=None):
    """Percent change vs generation 0."""
    gs, ms = series(arms, arm, metric, upto)
    if not gs:
        return [], []
    base = ms[0]
    return gs, [(m - base) / base * 100.0 for m in ms]


def cal_gap(arms, arm, gen, suffix=""):
    """log(PPL) - entropy, per seed then averaged. Absolute nats."""
    p = seed_vals(arms, arm, "ppl" + suffix, gen)
    e = seed_vals(arms, arm, "entropy" + suffix, gen)
    seeds = sorted(set(p) & set(e))
    return sum(math.log(p[s]) - e[s] for s in seeds) / len(seeds)


def abruptness(arms, arm, metric, upto=None):
    """max single-generation |delta| / total |delta|, in percent."""
    gs, ms = series(arms, arm, metric, upto)
    if len(gs) < 2:
        return None
    total = abs(ms[-1] - ms[0])
    if total == 0:
        return None
    step = max(abs(ms[i + 1] - ms[i]) for i in range(len(ms) - 1))
    return step / total * 100.0


