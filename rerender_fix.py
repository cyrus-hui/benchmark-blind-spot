def fig2_first_signal(arms, out):
    try:
        from scipy import stats
    except ImportError:
        print("  fig2 needs scipy (pip install scipy) — skipped", file=sys.stderr)
        return None

    order = [m[0] for m in METRICS]
    ypos = {lab: len(order) - 1 - i for i, lab in enumerate(order)}
    fig, ax = plt.subplots(figsize=(7.2, 3.4))

    for arm, label, n, last, colour, _ls in ARMS:
        marker = "o" if "topk" in arm else "D"
        for disp, key, direction in METRICS:
            if key not in arms[arm]:
                continue
            gs = [g for g in gens(arms, arm, key) if g <= last]
            base = seed_vals(arms, arm, key, 0)
            seeds = sorted(base)
            first = None
            for g in gs[1:]:
                cur = seed_vals(arms, arm, key, g)
                a = np.array([base[s] for s in seeds])
                b = np.array([cur[s] for s in seeds if s in cur])
                if len(b) != len(a):
                    continue
                diff = b - a if direction == "up" else a - b
                if np.allclose(diff, 0):
                    continue
                t, p = stats.ttest_rel(b, a)
                p_one = p / 2 if (diff.mean() > 0) else 1.0
                if p_one < 0.05 and diff.mean() > 0:
                    first = g
                    break
            y = ypos[disp] + (0.22 if "gpt2" in arm else -0.22) + (0.08 if "greedy" in arm else -0.08)
            if first is not None:
                ax.plot(first, y, marker, color=colour, markersize=4,
                        markerfacecolor=colour if "topk" in arm else "none")
            else:
                ax.annotate("", xy=(last + 0.6, y), xytext=(last - 0.6, y),
                            arrowprops=dict(arrowstyle="->", color=colour, lw=0.9, ls=":"))

    ax.axhline(ypos["Emb. variance"] - 0.5, color="0.5", lw=0.7, ls=":")
    ax.text(12.4, ypos["Emb. variance"] - 0.35, "collapse metrics", fontsize=6,
            color="0.45", ha="right")
    ax.text(12.4, ypos["Emb. variance"] - 0.85, "benchmarks (detectors under test)",
            fontsize=6, color="0.45", ha="right")
    ax.set_yticks([ypos[l] for l in order])
    ax.set_yticklabels(order)
    ax.set_xlim(0.3, 13.2)
    ax.set_xticks([1, 2, 4, 6, 8, 10, 12])
    ax.set_xlabel("first generation with $p<0.05$ in the collapse direction (paired, vs gen 0)")
    ax.set_title("Diversity and distributional metrics fire at generation 1; "
                 "benchmarks lag or never fire")
    ax.spines[["top", "right", "left"]].set_visible(False)
    handles = [plt.Line2D([], [], marker="o" if "topk" in a[0] else "D", ls="",
                          color=a[4], markerfacecolor=a[4] if "topk" in a[0] else "none",
                          label=a[1]) for a in ARMS]
    ax.legend(handles=handles, loc="upper right", frameon=False, fontsize=6)
    fig.savefig(out, format="pdf")
    plt.close(fig)
    print("  NOTE fig2: significance markers are recomputed here. The paper's "
          "version also carries hand-set 'not diagnostic' grey markers and Holm "
          "annotations. Compare against the current PDF before shipping.",
          file=sys.stderr)
    return out


